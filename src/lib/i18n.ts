export function getRoleLanguage(role: string): Lang {
  switch (role) {
    case 'staff_qa':
    case 'spv_qc':
      return 'en';
    case 'manager_qc':
    case 'manager_umum':
      return 'zh';
    default:
      return 'zh';
  }
}

